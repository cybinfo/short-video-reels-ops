#!/usr/bin/env python3
"""Auto-discover episode manifests and generate engine/src/generated/episodeRegistry.ts."""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_EPISODES_DIR = REPO_ROOT / "episodes"
DEFAULT_OUTPUT_PATH = REPO_ROOT / "engine" / "src" / "generated" / "episodeRegistry.ts"
DEFAULT_AUDIO_DIR = REPO_ROOT / "engine" / "public" / "audio"

SKIP_DIR_NAMES = {"briefs", "audio", "__pycache__", "node_modules"}


def _is_skipped_filename(name: str) -> bool:
    if name.startswith(".") or name.endswith(("~", ".tmp")):
        return True
    lower = name.lower()
    if lower == "schema.json" or lower.endswith(".brief.json"):
        return True
    return not lower.endswith(".json")


def _load_manifest_sort_key(path: Path) -> tuple[int, int, str] | None:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    if not isinstance(data, dict) or "id" not in data or "scenes" not in data:
        return None
    season = int(data.get("season", 999))
    ep_num = int(data.get("episode", data.get("episodeNumber", 999)))
    ep_id = str(data.get("id", path.stem))
    return (season, ep_num, ep_id)


def discover_episode_manifests(episodes_dir: Path | None = None) -> list[Path]:
    """Scan episodes/**/*.json sorted by (season, episodeNumber, id), skipping schema & briefs."""
    root = (episodes_dir or DEFAULT_EPISODES_DIR).resolve()
    if not root.is_dir():
        return []

    keyed_paths: list[tuple[tuple[int, int, str], Path]] = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(
            d for d in dirnames if not d.startswith(".") and d.lower() not in SKIP_DIR_NAMES
        )
        cur_dir = Path(dirpath)
        rel_parts = cur_dir.relative_to(root).parts
        if any(p.startswith(".") or p.lower() in SKIP_DIR_NAMES for p in rel_parts):
            continue
        for fname in sorted(filenames):
            if _is_skipped_filename(fname):
                continue
            candidate = (cur_dir / fname).resolve()
            sort_key = _load_manifest_sort_key(candidate)
            if sort_key is not None:
                keyed_paths.append((sort_key, candidate))

    keyed_paths.sort(key=lambda item: item[0])
    return [p for _, p in keyed_paths]


def _rel_import_path(target: Path, from_dir: Path) -> str:
    rel = Path(os.path.relpath(target.resolve(), from_dir.resolve())).as_posix()
    return rel if rel.startswith(".") else f"./{rel}"


def _safe_ident(prefix: str, idx: int, ep_id: str) -> str:
    slug = re.sub(r"[^a-zA-Z0-9_]", "_", ep_id).strip("_")
    return f"{prefix}_{idx:02d}_{slug}"


def sync_registry(
    episodes_dir: Path | None = None,
    output_path: Path | None = None,
    audio_dir: Path | None = None,
) -> list[Path]:
    """Generate engine/src/generated/episodeRegistry.ts and return discovered manifest paths."""
    manifests = discover_episode_manifests(episodes_dir)
    out_file = (output_path or DEFAULT_OUTPUT_PATH).resolve()
    aud_dir = (audio_dir or DEFAULT_AUDIO_DIR).resolve()
    out_dir = out_file.parent
    out_dir.mkdir(parents=True, exist_ok=True)

    manifest_imports: list[str] = []
    caption_imports: list[str] = []
    episode_items: list[str] = []
    caption_entries: list[str] = []

    for idx, m_path in enumerate(manifests):
        data = json.loads(m_path.read_text(encoding="utf-8"))
        ep_id = str(data["id"])
        raw_ident = _safe_ident("epRaw", idx, ep_id)
        m_rel = _rel_import_path(m_path, out_dir)
        manifest_imports.append(f"import {raw_ident} from {json.dumps(m_rel)};")
        episode_items.append(f"  {raw_ident} as unknown as EpisodeManifest,")

        cap_path = aud_dir / f"{ep_id}.captions.json"
        if cap_path.is_file():
            cap_ident = _safe_ident("epCaptions", idx, ep_id)
            c_rel = _rel_import_path(cap_path, out_dir)
            caption_imports.append(f"import {cap_ident} from {json.dumps(c_rel)};")
            caption_entries.append(f"  {json.dumps(ep_id)}: {cap_ident} as WordTimestamp[],")
        else:
            caption_entries.append(f"  {json.dumps(ep_id)}: [] as WordTimestamp[],")

    lines: list[str] = [
        "// Auto-generated by scripts/sync_episode_registry.py — DO NOT EDIT MANUALLY.",
        "import type {EpisodeManifest, WordTimestamp} from '../types';",
        *manifest_imports,
        *caption_imports,
        "",
        "export const EPISODES: EpisodeManifest[] = [",
        *episode_items,
        "];",
        "",
        "export const CAPTIONS_BY_ID: Record<string, WordTimestamp[]> = {",
        *caption_entries,
        "};",
        "",
    ]
    content = "\n".join(lines)
    if not out_file.is_file() or out_file.read_text(encoding="utf-8") != content:
        out_file.write_text(content, encoding="utf-8")
    return manifests


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--episodes-dir", type=Path, default=None, help="Episodes root directory")
    parser.add_argument("--output", type=Path, default=None, help="Generated TypeScript registry path")
    parser.add_argument("--quiet", action="store_true", help="Suppress summary output")
    args = parser.parse_args(argv)

    manifests = sync_registry(episodes_dir=args.episodes_dir, output_path=args.output)
    if not args.quiet:
        out_target = (args.output or DEFAULT_OUTPUT_PATH).resolve()
        rel_out = out_target.relative_to(REPO_ROOT) if out_target.is_relative_to(REPO_ROOT) else out_target
        print(f"Synced {len(manifests)} episode manifest(s) -> {rel_out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
